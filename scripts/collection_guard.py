"""Hourly wake-up with a three-hour freshness gate; no synthetic captures."""
import argparse
import datetime as dt
import hashlib
import json
import os
import re
from pathlib import Path
from announcement_history import timestamp, valid_reaction_quote
from collection_policy import EXPECTED_CADENCE_HOURS


def decision(root, event, at):
    if event != 'schedule':
        return {'collect': True, 'reason': 'EXPLICIT_OR_CODE_TRIGGER'}
    current = timestamp(at)
    if current is None:
        raise ValueError('Invalid gate time')
    try:
        pointer = json.loads((root / 'latest.json').read_text())
        sid = pointer['snapshot_id']
        if pointer.get('schema') != 'edge.public.live_capture.v1' or not re.fullmatch(r'[0-9]+-[0-9]+', sid):
            raise ValueError('Invalid pointer')
        entry = pointer['files']['report.json']
        if entry['path'] != 'snapshots/' + sid + '/report.json':
            raise ValueError('Invalid snapshot path')
        raw = (root / entry['path']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != entry['sha256']:
            raise ValueError('Invalid snapshot checksum')
        report = json.loads(raw)
        stamp = timestamp(report['observed_at'])
        if (report.get('schema') != 'edge.commercial.snapshot.v1' or stamp is None
                or report['observed_at'] != pointer['observed_at'] or report['status'] != pointer['status']):
            raise ValueError('Inconsistent snapshot')
        age = (current - stamp).total_seconds() / 3600
        if age < 0:
            raise ValueError('Future snapshot')
        usable = any(r.get('status') == 'OK' and r.get('price_kind') == 'ASKING_PRICE'
                     and r.get('currency') == 'EUR' and valid_reaction_quote(r)
                     and 0 <= (current-timestamp(r['observed_at'])).total_seconds() < EXPECTED_CADENCE_HOURS*3600
                     for r in report['observations'])
        if report['status'] in ('OK', 'PARTIAL') and age < EXPECTED_CADENCE_HOURS and usable:
            return {'collect': False, 'reason': 'VERIFIED_CAPTURE_STILL_RECENT', 'snapshot_id': sid,
                    'observed_at': report['observed_at'], 'age_hours': age}
        return {'collect': True, 'reason': 'CAPTURE_DUE_OR_NO_RECENT_RETAIL_PROOF', 'snapshot_id': sid,
                'observed_at': report['observed_at'], 'age_hours': age}
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return {'collect': True, 'reason': 'LATEST_CAPTURE_UNVERIFIABLE'}


def trigger_context(environ):
    event = environ.get('GITHUB_EVENT_NAME', 'local')
    event = event if event in ('schedule', 'push', 'workflow_dispatch', 'local') else 'other'
    run_id = environ.get('GITHUB_RUN_ID', '')
    attempt = environ.get('GITHUB_RUN_ATTEMPT', '')
    return {'event': event, 'run_id': run_id if run_id.isdigit() else None,
            'run_attempt': int(attempt) if attempt.isdigit() else None,
            'schedule_is_delivery_guarantee': False}


def main():
    cli = argparse.ArgumentParser()
    cli.add_argument('--history', required=True)
    cli.add_argument('--event', required=True)
    args = cli.parse_args()
    at = dt.datetime.now(dt.timezone.utc).isoformat()
    result = decision(Path(args.history), args.event, at)
    print(json.dumps(result))
    if os.environ.get('GITHUB_OUTPUT'):
        with open(os.environ['GITHUB_OUTPUT'], 'a') as f:
            f.write('collect=' + str(result['collect']).lower() + '\n')
    if os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a') as f:
            f.write('## Collection freshness gate\n\n' + result['reason'] + '\n\n')
            f.write('Collect now: ' + str(result['collect']) + '. No observation is generated by this gate.\n')


if __name__ == '__main__':
    main()
